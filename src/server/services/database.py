import json
import logging
import os
import threading
import time
from pathlib import Path
from typing import List, Optional

from ..entities.dto import Project, ProjectStatus
from .storage import DATA_DIR, write_json_atomic

logger = logging.getLogger("project_hub")

PROJECTS_FILE = "projects.json"
ARCHIVED_PROJECTS_FILE = "projects_archived.json"


class DatabaseError(Exception):
    """Raised when the projects cannot be persisted."""


class ProjectsDatabase:
    """The projects of one user, kept in memory and stored in `directory`.

    Active and archived projects live in separate files.
    """

    def __init__(self, directory: Path):
        self.directory = directory
        self.file = directory / PROJECTS_FILE
        self.archived_file = directory / ARCHIVED_PROJECTS_FILE
        self._projects_storage: List[Project] = []
        self._archived_projects_storage: List[Project] = []
        self._lock = threading.Lock()

    def get_projects(self) -> List[Project]:
        return [p for p in self._projects_storage + self._archived_projects_storage if p is not None]

    def load_from_disk(self):
        self._archived_projects_storage = self.load_json_file(self.archived_file)
        self._projects_storage = self.load_json_file(self.file)

    def save_to_disk(self, incoming_projects: List[Project]):
        """Persists the projects, splitting active and archived into separate files.

        Files are written atomically and the in-memory state only changes
        once both files are safely on disk.
        """
        sanitized = self.sanitize_projects(incoming_projects)
        with self._lock:
            try:
                self._write_json_atomic(self.file, sanitized["active"])
                self._write_json_atomic(self.archived_file, sanitized["archived"])
            except OSError as e:
                raise DatabaseError(f"Failed to save projects: {e}") from e

            self._projects_storage = sanitized["active"]
            self._archived_projects_storage = sanitized["archived"]

    def sanitize_projects(self, projects: List[Project]) -> dict[str, List[Project]]:
        """Splits projects into archived and non-archived (active / not started)."""
        archived = [p for p in projects if p.status == ProjectStatus.ARCHIVED]
        active = [p for p in projects if p.status != ProjectStatus.ARCHIVED]
        return {"active": active, "archived": archived}

    def load_json_file(self, file_path: Path) -> List[Project]:
        """Loads projects from a specified JSON file."""
        if file_path.exists() and file_path.stat().st_size > 0:
            try:
                with open(file_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    return [Project(**p) for p in data] if data else []
            except Exception as e:
                logger.warning("Load error from %s: %s", file_path, e)
                return []
        return []

    @staticmethod
    def _write_json_atomic(path: Path, projects: List[Project]):
        write_json_atomic(path, [p.model_dump(mode="json") for p in projects])


class DatabaseRegistry:
    """One ProjectsDatabase per user, stored in `<data_dir>/users/<user_id>/` and loaded on first use."""

    def __init__(self, data_dir: Optional[Path] = None):
        self.data_dir = Path(data_dir or DATA_DIR)
        self.users_dir = self.data_dir / "users"
        self.trash_dir = self.data_dir / "deleted"
        self._databases: dict[str, ProjectsDatabase] = {}
        self._lock = threading.Lock()

    def user_dir(self, user_id: str) -> Path:
        # User ids are generated by the server (hex), but never trust them as path components.
        if not user_id or not user_id.isalnum():
            raise ValueError(f"Invalid user id: {user_id!r}")
        return self.users_dir / user_id

    def get(self, user_id: str) -> ProjectsDatabase:
        with self._lock:
            db = self._databases.get(user_id)
            if db is None:
                db = ProjectsDatabase(self.user_dir(user_id))
                db.load_from_disk()
                self._databases[user_id] = db
            return db

    def trash(self, user_id: str) -> Optional[Path]:
        """Moves a user's data to `<data_dir>/deleted/<user_id>-<timestamp>/`; returns the new path."""
        with self._lock:
            self._databases.pop(user_id, None)
            source = self.user_dir(user_id)
            if not source.exists():
                return None
            self.trash_dir.mkdir(parents=True, exist_ok=True)
            target = self.trash_dir / f"{user_id}-{time.strftime('%Y%m%d-%H%M%S')}"
            os.replace(source, target)
            return target

    def adopt_legacy_data(self, user_id: str) -> bool:
        """Moves pre-multi-user data (`<data_dir>/projects*.json`) into the user's folder.

        Only happens when that user has no data yet, so nothing is ever overwritten.
        """
        legacy = [self.data_dir / PROJECTS_FILE, self.data_dir / ARCHIVED_PROJECTS_FILE]
        legacy = [f for f in legacy if f.exists()]
        target = self.user_dir(user_id)
        if not legacy or (target / PROJECTS_FILE).exists() or (target / ARCHIVED_PROJECTS_FILE).exists():
            return False
        with self._lock:
            target.mkdir(parents=True, exist_ok=True)
            for f in legacy:
                os.replace(f, target / f.name)
            self._databases.pop(user_id, None)
        return True
